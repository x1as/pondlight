def main():
    out_dir = os.path.join(GAME, "assets", "fonts")
    os.makedirs(out_dir, exist_ok=True)
    chars = [ch for ch in G.keys() if ch != " "]
    tex_w, cell_h = 256, 10
    x, y = 1, 1
    placements = []
    img = Image.new("RGBA", (tex_w, 128), (0, 0, 0, 0))
    px = img.load()
    for ch in chars:
        rows = G[ch].split("|")
        w = len(rows[0])
        if x + w + 1 >= tex_w:
            x = 1
            y += cell_h + 1
        for ry, row in enumerate(rows):
            assert len(row) == w, (ch, rows)
            for rx, v in enumerate(row):
                if v == "#":
                    px[x + rx, y + ry] = (255, 255, 255, 255)
        placements.append((ch, x, y, w, len(rows)))
        x += w + 2
    img.save(os.path.join(out_dir, "pond_font.png"))
    lines = [
        'info face="Pondlight" size=10 bold=0 italic=0 charset="" unicode=1 stretchH=100 smooth=0 aa=0 padding=0,0,0,0 spacing=1,1 outline=0',
        f'common lineHeight=11 base=9 scaleW={tex_w} scaleH=128 pages=1 packed=0 alphaChnl=0 redChnl=4 greenChnl=4 blueChnl=4',
        'page id=0 file="pond_font.png"',
        f"chars count={len(placements) + 1}",
        "char id=32 x=0 y=0 width=0 height=0 xoffset=0 yoffset=0 xadvance=4 page=0 chnl=15",
    ]
    for ch, cx, cy, w, h in placements:
        lines.append(f"char id={ord(ch)} x={cx} y={cy} width={w} height={h} xoffset=0 yoffset=2 xadvance={w + 1} page=0 chnl=15")
    with open(os.path.join(out_dir, "pond_font.fnt"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("font done", len(placements))


if __name__ == "__main__":
    main()
